def normalized_text(value):
    """Conservatively join repeated references despite spaces or punctuation."""
    return ''.join(c for c in unicodedata.normalize('NFKC',value).casefold()
                   if not c.isspace() and unicodedata.category(c)[0] not in {'P','C'})

